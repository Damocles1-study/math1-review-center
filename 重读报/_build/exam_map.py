def weights(years=PAPER_YEARS):
    """每期平均每卷多少分"""
    w = {}
    for y in years:
        for n, s in zip(MAP[y], scores(y)):
            w[n] = w.get(n, 0) + s
    return {n: round(v / len(years), 1) for n, v in w.items()}


